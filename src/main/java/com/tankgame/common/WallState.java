package com.tankgame.common;

public class WallState {
    public double x;
    public double y;
    public double w;
    public double h;

    public WallState() {
    }

    public WallState(double x, double y, double w, double h) {
        this.x = x;
        this.y = y;
        this.w = w;
        this.h = h;
    }
}
